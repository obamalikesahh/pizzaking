const menuPath = './src/data/menu.js';
const fileContent = fs.readFileSync(menuPath, 'utf8');

const regex = /export const menuData = (\[[\s\S]*\]);/;
const match = fileContent.match(regex);
if (match) {
  let menuData = eval(match[1]);

  let updatedCount = 0;
  menuData.forEach(cat => {
    cat.items.forEach(item => {
      if (updates[item.id]) {
        if (updates[item.id].price) item.price = updates[item.id].price;
        if (updates[item.id].name) item.name = updates[item.id].name;
        updatedCount++;
      }
    });
  });

  const updatedContent = fileContent.replace(regex, 'export const menuData = ' + JSON.stringify(menuData, null, 2) + ';');
  fs.writeFileSync(menuPath, updatedContent, 'utf8');
  console.log(`Successfully updated ${updatedCount} items.`);
} else {
  console.error("Could not parse menu.js");
}
